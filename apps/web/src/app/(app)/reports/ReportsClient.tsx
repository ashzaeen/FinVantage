"use client";

import Link from "next/link";
import { useEffect, useRef, useState, type ReactNode } from "react";
import { CircleDollarSign, PiggyBank, TrendingDown, Wallet } from "lucide-react";
import { formatUsd, type InvestmentsOverview, type QuarterlyReport, type SpendingCategory, type SpendingSummary } from "@finvantage/contracts";
import { ProbabilityRange } from "@/components/finance/ProbabilityRange";
import { Card } from "@/components/ui/Card";
import { api, API_TOKEN, API_URL, currentToken } from "@/lib/api";
import { shortDate } from "@/lib/subscriptions";
import { QuarterlyReportCharts } from "./QuarterlyReportCharts";
import { longDate } from "@/lib/format";
import { buttonClass } from "@/components/ui/Button";

/** Same icon and color palette as the Overview page's stat cards, so the two pages read as one system. */
const SUMMARY_STAT_STYLE = [
  { label: "Net Worth", icon: <Wallet size={22} strokeWidth={2} aria-hidden="true" />, iconBg: "var(--accent-soft)", iconColor: "var(--accent-ink)", },
  { label: "Monthly Income", icon: <CircleDollarSign size={22} strokeWidth={2} aria-hidden="true" />, iconBg: "var(--accent-soft)", iconColor: "var(--accent-ink)", },
  { label: "Monthly Spending", icon: <TrendingDown size={22} strokeWidth={2} aria-hidden="true" />, iconBg: "var(--accent-soft)", iconColor: "var(--accent-ink)", },
  { label: "Monthly Savings", icon: <PiggyBank size={22} strokeWidth={2} aria-hidden="true" />, iconBg: "var(--accent-soft)", iconColor: "var(--accent-ink)", },
] as const;

function ReportSection({
  title,
  children,
  className = "",
}: {
  title: string;
  children: ReactNode;
  className?: string;
}) {
  return (
    <section className={`rounded-3xl border border-line bg-raised p-6 [box-shadow:var(--shadow-card)] ${className}`}>
      <h2 className="mb-4 font-poppins text-xl font-bold tracking-tight text-ink">{title}</h2>
      {children}
    </section>
  );
}

export function ReportsClient({ initialReports }: { initialReports: QuarterlyReport[] }) {
  const [reports, setReports] = useState(initialReports);
  const [selectedReportId, setSelectedReportId] = useState(initialReports[0]?.id ?? null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [showCharts, setShowCharts] = useState(true);
  const [chartsLoading, setChartsLoading] = useState(false);
  const [chartsError, setChartsError] = useState<string | null>(null);
  const [investments, setInvestments] = useState<InvestmentsOverview | null>(null);
  const [investmentsError, setInvestmentsError] = useState<string | null>(null);
  const [currentSpending, setCurrentSpending] = useState<{ summary: SpendingSummary; categories: SpendingCategory[] } | null>(null);
  // The PDF link is a plain download, so it carries the signed-in user's token in the URL.
  const [pdfToken, setPdfToken] = useState(API_TOKEN);
  useEffect(() => {
    void currentToken().then(setPdfToken);
  }, []);
  useEffect(() => {
    void Promise.all([api.getSpendingSummary(), api.listSpendingCategories()]).then(([summary, categories]) => {
      setCurrentSpending({ summary, categories });
    }).catch(() => {
      setCurrentSpending(null);
    });
  }, []);
  useEffect(() => {
    void api.getInvestments().then(setInvestments).catch((caught) => {
      setInvestmentsError(caught instanceof Error ? caught.message : "Could not load investment data.");
    });
  }, []);
  const latest = reports.find((report) => report.id === selectedReportId) ?? reports[0] ?? null;

  async function generate(quarter?: QuarterlyReport["quarter"]) {
    setBusy(true);
    setError(null);
    try {
      const report = await api.generateReport({
        body: { email: false, ...(quarter ? { quarter } : {}) },
      });
      setReports((current) => [report, ...current.filter((item) => item.id !== report.id)]);
      setSelectedReportId(report.id);
      setChartsLoading(true);
      try {
        setReports(await api.listReports());
        setChartsError(null);
      } catch (chartError) {
        setChartsError(chartError instanceof Error ? chartError.message : "Could not refresh report charts.");
      } finally {
        setChartsLoading(false);
      }
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : "Report generation failed.");
    } finally {
      setBusy(false);
    }
  }

  // A first visit should not open on a button: build the latest quarter right away. One try only,
  // so a failure leaves the button and the error rather than looping.
  const autoGenerated = useRef(false);
  useEffect(() => {
    if (initialReports.length > 0 || autoGenerated.current) return;
    autoGenerated.current = true;
    void generate();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  if (!latest) {
    return (
      <div className="space-y-5 text-ink">
        <Card title="Latest Quarter">
          <p className="text-sm text-muted">
            {busy
              ? "Building your first quarterly report from your accounts, goals and spending. This takes a few seconds."
              : "Reports can start from one saved quarter and add comparisons when a prior quarter exists."}
          </p>
          <button
            onClick={() => generate()}
            disabled={busy}
            className={buttonClass({}, "mt-4")}
          >
            {busy ? "Generating..." : "Generate Latest Report"}
          </button>
          {error && <p className="mt-3 text-sm text-loss">{error}</p>}
        </Card>
      </div>
    );
  }

  return (
    <div className="space-y-6 text-ink">
      <div className="flex flex-wrap items-center justify-between gap-3 rounded-2xl border border-line bg-raised p-3 shadow-sm">
        <div className="flex gap-2 overflow-x-auto no-scrollbar" aria-label="Generated quarterly reports">
          {[...reports].sort((left, right) => left.quarter.localeCompare(right.quarter)).map((report) => (
            <button
              key={report.id}
              type="button"
              onClick={() => setSelectedReportId(report.id)}
              aria-pressed={report.id === latest.id}
              className={
                report.id === latest.id
                  ? "min-w-24 rounded-xl bg-accent px-4 py-2.5 text-sm font-semibold text-white shadow-sm outline-none focus-visible:ring-2 focus-visible:ring-accent-ink focus-visible:ring-offset-2"
                  : "min-w-24 rounded-xl border border-line bg-inset px-4 py-2.5 text-sm font-semibold text-muted transition hover:border-accent-ink hover:text-accent-ink focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent-ink"
              }
            >
              {report.quarter}
            </button>
          ))}
        </div>
        <div className="flex flex-wrap items-center gap-2">
          {latest.pdf.status === "ready" && (
            <a
              className={buttonClass()}
              href={`${API_URL}/v1/reports/quarterly/${latest.id}/pdf?token=${encodeURIComponent(pdfToken)}`}
            >
              Download PDF
            </a>
          )}
          {/* Rebuilds this quarter from current data: a linked bank, new simulations, fresh prose. */}
          <button
            type="button"
            className="rounded-xl border border-line bg-raised px-4 py-2.5 text-sm font-semibold text-ink transition hover:bg-inset focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent-ink disabled:opacity-50"
            onClick={() => generate(latest.quarter)}
            disabled={busy}
          >
            {busy ? "Regenerating..." : "Regenerate"}
          </button>
          <button
            type="button"
            className="rounded-xl border border-line bg-raised px-4 py-2.5 text-sm font-semibold text-ink transition hover:bg-inset focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent-ink"
            onClick={() => setShowCharts((visible) => !visible)}
          >
            {showCharts ? "Hide Charts" : "Show Charts"}
          </button>
        </div>
      </div>

      {error && <p className="rounded-xl bg-critical-bg p-3 text-sm text-loss">{error}</p>}

      <p className="text-sm text-muted">
        {latest.visuals.dataSource === "bank" ? (
          "Based on your linked bank accounts."
        ) : (
          <>
            Based on sample data.{" "}
            <Link href="/accounts" className="font-semibold text-accent-ink hover:underline">
              Link a bank
            </Link>{" "}
            to use your own.
          </>
        )}
        {latest.visuals.outlookAsOf && ` Goal outlook as of ${longDate(latest.visuals.outlookAsOf)}.`}
      </p>

      <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 xl:grid-cols-4">
        {[
          formatUsd(latest.visuals.summary.netWorthCents),
          formatUsd(latest.visuals.summary.monthlyIncomeCents),
          formatUsd(latest.visuals.summary.monthlySpendingCents),
          formatUsd(latest.visuals.summary.monthlySavingsCents),
        ].map((value, index) => {
          const style = SUMMARY_STAT_STYLE[index]!;
          return (
            <div key={style.label} className="rounded-2xl border border-line p-4 shadow-sm transition hover:-translate-y-0.5 hover:shadow-[0_8px_30px_-4px_rgba(84,74,247,0.08)]" >
              <span className="flex h-11 w-11 items-center justify-center rounded-2xl" style={{ background: style.iconBg, color: style.iconColor }}>{style.icon}</span>
              <span className="mt-3 block text-xs font-semibold uppercase tracking-[0.12em] text-muted">{style.label}</span>
              <p className="mt-1 text-right font-poppins text-2xl font-bold tabular-nums text-ink">{value}</p>
              <p className="mt-1 text-right text-xs text-muted">
                {latest.visuals.dataSource === "bank" ? "From your linked banks" : "Saved planning figure"}
              </p>
            </div>
          );
        })}
      </div>

      {showCharts && (
        <QuarterlyReportCharts reports={[latest]} loading={chartsLoading} error={chartsError} investments={investments} investmentsError={investmentsError} currentSpending={currentSpending} />
      )}

      <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
        <ReportSection title="What Went Well">
          <ul className="space-y-3 text-sm">
            {latest.wentWell.map((item) => <li key={item} className="flex gap-3"><span className="mt-1 h-2 w-2 shrink-0 rounded-full bg-good" />{item}</li>)}
          </ul>
        </ReportSection>
        <ReportSection title="Needs Attention">
          <ul className="space-y-3 text-sm">
            {latest.didNotGoWell.map((item) => <li key={item} className="flex gap-3"><span className="mt-1 h-2 w-2 shrink-0 rounded-full bg-warning" />{item}</li>)}
          </ul>
        </ReportSection>
      </div>

      <ReportSection title="Why It Changed">
        <p className="text-sm">{latest.why}</p>
        {latest.largestChange ? (
          <div className="mt-4 border-t border-line pt-4">
            <p className="text-sm font-medium">{latest.largestChange.label}</p>
            <p className="mt-1 text-sm text-muted">
              Previous: {latest.largestChange.previousValue}. Current: {latest.largestChange.currentValue}. {latest.largestChange.change}.
            </p>
            <p className="mt-2 text-sm">{latest.largestChange.cause}</p>
          </div>
        ) : (
          <p className="mt-4 border-t border-line pt-4 text-sm text-muted">
            This is the first available quarterly baseline, so no previous-quarter comparison is shown.
          </p>
        )}
      </ReportSection>

      <ReportSection title="Supporting Numbers">
        <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
          {latest.evidence.map((item) => (
            <div key={`${item.quarter}-${item.sourceId}`}>
              <p className="text-sm font-medium">{item.quarter}</p>
              <p className="text-xs text-muted">{item.label}</p>
              {item.probabilityLow !== null && item.probabilityHigh !== null ? (
                <ProbabilityRange low={item.probabilityLow} high={item.probabilityHigh} />
              ) : (
                <p className="text-sm">{item.value}</p>
              )}
            </div>
          ))}
        </div>
      </ReportSection>

      <ReportSection title="What We Checked">
        <div className="grid grid-cols-1 gap-3 sm:grid-cols-3">
          <div className="rounded-xl bg-inset p-4">
            <p className="text-right font-poppins text-2xl font-bold tabular-nums">{latest.sourceIds.simulationRunIds.length}</p>
            <p className="text-xs text-muted">Simulation Runs Reviewed</p>
          </div>
          <div className="rounded-xl bg-inset p-4">
            <p className="text-right font-poppins text-2xl font-bold tabular-nums">{latest.sourceIds.copilotEventIds.length}</p>
            <p className="text-xs text-muted">Copilot Events Reviewed</p>
          </div>
          <div className="rounded-xl bg-inset p-4">
            <p className="text-right font-poppins text-2xl font-bold tabular-nums">{latest.sourceIds.recommendationIds.length}</p>
            <p className="text-xs text-muted">Recommendations Reviewed</p>
          </div>
        </div>
      </ReportSection>

      {latest.visuals.subscriptions && (
        <ReportSection title="Subscriptions">
          {(() => {
            const subs = latest.visuals.subscriptions!;
            const compare =
              subs.changeCents === null
                ? "There is not enough history to compare with last quarter."
                : subs.changeCents === 0
                  ? "That is the same as last quarter."
                  : `That is ${formatUsd(Math.abs(subs.changeCents))} ${subs.changeCents > 0 ? "more" : "less"} than last quarter.`;
            return (
              <div className="space-y-3 text-sm leading-6 normal-case">
                <p>
                  You were charged <span className="font-semibold tabular-nums">{formatUsd(subs.spendCents)}</span> across {subs.chargedCount}{" "}
                  {subs.chargedCount === 1 ? "subscription" : "subscriptions"} this quarter. {compare}
                </p>
                {subs.cancelled.length > 0 && (
                  <ul className="space-y-1">
                    {subs.cancelled.map((c) => (
                      <li key={`${c.merchant}-${c.cancelledOn}`} className="rounded-xl bg-inset px-3 py-2">
                        You marked <span className="font-semibold">{c.merchant}</span> as cancelled on {shortDate(c.cancelledOn)}
                        {c.monthlyCents !== null && `, which was ${formatUsd(c.monthlyCents)} a month`}.
                      </li>
                    ))}
                  </ul>
                )}
                <Link href="/subscriptions" className="inline-block font-semibold text-accent-ink hover:underline">
                  See Subscriptions
                </Link>
              </div>
            );
          })()}
        </ReportSection>
      )}

      <ReportSection title="Goal Outlook">
        <div className="grid grid-cols-1 gap-3 lg:grid-cols-2">
          {latest.visuals.goalPathways.map((goal) => (
            <div key={goal.goalId} className="rounded-2xl border border-line bg-inset/50 p-4">
              <div className="flex flex-wrap items-start justify-between gap-2">
                <div>
                  <p className="font-semibold">{goal.goalName}</p>
                  <p className="text-xs text-muted">
                    Target {formatUsd(goal.targetCents)} by {longDate(goal.targetDate)}
                  </p>
                </div>
                <span className="rounded-lg border border-line bg-raised px-2 py-1 text-xs font-semibold uppercase text-accent-ink">
                  {goal.status.replaceAll("_", " ")}
                </span>
              </div>
              <div className="mt-3">
                <ProbabilityRange low={goal.probabilityLow} high={goal.probabilityHigh} />
              </div>
              <p className="mt-2 text-xs text-muted">
                Median completion: {goal.medianCompletionDate ?? "not established in this simulation"}
              </p>
            </div>
          ))}
        </div>
      </ReportSection>

      <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
        <ReportSection title="Look Ahead"><p className="text-sm leading-6">{latest.lookAhead}</p></ReportSection>
        <ReportSection title="Next Steps">
          <ol className="list-decimal space-y-2 pl-5 text-sm">
            {latest.nextSteps.map((step) => <li key={step}>{step}</li>)}
          </ol>
        </ReportSection>
      </div>

      <ReportSection title="Suggested Focus">
        <div className="grid grid-cols-1 gap-3 md:grid-cols-3">
          {latest.visuals.suggestions.map((suggestion) => (
            <div key={suggestion.goalId} className="rounded-2xl border border-line bg-inset/50 p-4">
              <p className="text-xs font-semibold uppercase tracking-[0.12em] text-accent-ink">{suggestion.category}</p>
              <p className="mt-1 text-sm font-medium">{suggestion.title}</p>
              <p className="mt-1 text-xs text-muted">{suggestion.detail}</p>
            </div>
          ))}
        </div>
      </ReportSection>

    </div>
  );
}
